#!/usr/bin/env node
/**
 * Scans web/public/avatars/gallery/ for image files and regenerates
 * web/lib/avatarGallery.ts so the page always shows exactly what exists.
 *
 * Run automatically via "prebuild" or manually with:
 *   node scripts/generate-avatar-gallery.mjs
 *
 * Supports any number of files and any names (jpg / jpeg / png / webp).
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const galleryDir = path.join(__dirname, "../public/avatars/gallery");
const outFile = path.join(__dirname, "../lib/avatarGallery.ts");

const IMAGE_EXTS = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif"]);

function main() {
  if (!fs.existsSync(galleryDir)) {
    console.warn("[generate-avatar-gallery] gallery folder missing, writing empty list");
    writeGallery([]);
    return;
  }

  const files = fs
    .readdirSync(galleryDir)
    .filter((name) => {
      const ext = path.extname(name).toLowerCase();
      return IMAGE_EXTS.has(ext) && !name.startsWith(".") && name !== "README.md";
    })
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  writeGallery(files);
  console.log(`[generate-avatar-gallery] Found ${files.length} avatars → ${outFile}`);
}

function writeGallery(files) {
  const list = files.map((f) => `  "${f}",`).join("\n");

  const content = `/**
 * AUTO-GENERATED by scripts/generate-avatar-gallery.mjs
 * Do not edit by hand. Run the script (or npm run build) after adding/removing files.
 *
 * Generated: ${new Date().toISOString()}
 * Count: ${files.length}
 */
export const AVATAR_GALLERY = [
${list}
] as const;

export type AvatarId = (typeof AVATAR_GALLERY)[number];

/** Returns the public URL for an avatar file (includes extension). */
export function avatarUrl(filename: string): string {
  return \`/avatars/gallery/\${filename}\`;
}
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, content, "utf8");
}

main();
